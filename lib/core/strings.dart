  bool get isRtl {
    final l = state.lang;
    if (l == AppLang.arabic) return true;
    if (l == AppLang.english) return false;
    // لغة النظام: نكتشف من الجهاز عند الاستخدام (تمرر من main)
    return defaultLocaleIsArabic;
  }

  String t(String key) {
    final l = state.lang;
    if (l == AppLang.arabic) return _ar[key] ?? key;
    if (l == AppLang.english) return _en[key] ?? key;
    return defaultLocaleIsArabic ? (_ar[key] ?? key) : (_en[key] ?? key);
  }
